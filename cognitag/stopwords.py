"""
ストップワード定義

【なぜ必要か】
5カテゴリでの試行で、上位30語のうち20語以上が
「こと」「もの」「ため」「使う」「なるほど」といった機能語で占められた。
これらに物理・心理・時間・論理の重みを付けても、応答生成には何の役にも立たない。
このまま本番を回すと辞書の大半が機能語で埋まり、注釈時間も浪費される。

【方針（B案）】
明確な機能語のみを除外し、抽象名詞（効果・方法・機能・素材など）は残す。
抽象名詞こそ CogniTag が LLM を近似する上で効く層であり、
かつ多義的で分散が出やすい語は隔離機構が自動的に振り分けるため。

各リストは用途別に分離してあるので、方針変更時に個別に切り替えられる。
"""

from __future__ import annotations

# 形式名詞: 実質的な意味を持たない名詞
FORMAL_NOUNS = {
    "こと", "もの", "ため", "場合", "とき", "時", "ところ", "所",
    "わけ", "はず", "つもり", "うち", "ほう", "方", "点", "際",
    "上", "中", "下", "他", "ほか", "内", "外", "前", "後",
    "以上", "以下", "以外", "など", "なか", "感じ", "気",
    "の", "ん", "こと自体", "ぶん", "分",
}

# 指示詞
DEMONSTRATIVES = {
    "これ", "それ", "あれ", "どれ",
    "ここ", "そこ", "あそこ", "どこ",
    "こう", "そう", "ああ", "どう",
    "この", "その", "あの", "どの",
    "こちら", "そちら", "あちら", "どちら",
    "こんな", "そんな", "あんな", "どんな",
}

# 汎用動詞: どの文脈にも現れ、意味を特定できない動詞
GENERIC_VERBS = {
    "する", "なる", "ある", "いる", "おる", "いく", "行く", "くる", "来る",
    "みる", "見る", "おく", "置く", "しまう", "くれる", "もらう", "あげる",
    "できる", "いう", "言う", "思う", "考える", "感じる",
    "使う", "持つ", "出る", "入る", "続ける", "始める", "終わる",
    "やる", "とる", "取る", "つく", "つける", "わかる", "分かる",
    "知る", "聞く", "話す", "教える", "だ", "です", "ます",
}

# 汎用副詞: 程度・頻度を表すが、それ自体は内容を持たない
GENERIC_ADVERBS = {
    "あと", "最近", "特に", "やはり", "やっぱり", "ちょっと",
    "すごく", "とても", "かなり", "もっと", "たくさん", "いろいろ",
    "少し", "本当", "確か", "実際", "結局", "まず", "もう",
    "また", "さらに", "ずっと", "いつも", "よく", "全然",
    "だいたい", "ほとんど", "たまに", "きっと", "たぶん",
    "そのまま", "一番", "一応", "実は", "例えば",
}

# 感動詞・相槌
INTERJECTIONS = {
    "なるほど", "そうそう", "ええ", "うん", "はい", "いいえ",
    "ありがとう", "すみません", "こんにちは", "さん", "ねえ",
    "わあ", "へえ", "ふむ", "おお",
}

# 汎用形容詞: 評価語だが内容を持たない
GENERIC_ADJECTIVES = {
    "いい", "良い", "よい", "悪い", "すごい", "だめ", "ダメ",
    "大きい", "小さい", "多い", "少ない", "高い", "低い",
    "新しい", "古い", "簡単", "難しい", "大切", "重要",
    "大丈夫", "必要", "可能",
}

# 会話コーパス特有のノイズ（対話の話者ラベル残骸など）
CORPUS_NOISE = {
    "さん", "私", "僕", "自分", "みたい", "感じ", "話",
    "以前", "今度", "今回", "今日", "最初", "最後",
}

STOPWORDS: frozenset[str] = frozenset(
    FORMAL_NOUNS
    | DEMONSTRATIVES
    | GENERIC_VERBS
    | GENERIC_ADVERBS
    | INTERJECTIONS
    | GENERIC_ADJECTIVES
    | CORPUS_NOISE
)

# Sudachi の細分類のうち、内容語として扱わないもの
EXCLUDED_SUBPOS: frozenset[str] = frozenset(
    {
        "数詞",
        "固有名詞",
        "代名詞",
        "非自立可能",
        "助数詞可能",
        "副詞可能",
        "形状詞可能",
    }
)

# 品詞そのものを除外
EXCLUDED_POS: frozenset[str] = frozenset(
    {"助詞", "助動詞", "感動詞", "接尾辞", "接頭辞", "補助記号", "記号", "空白"}
)


def is_stopword(word: str) -> bool:
    return word in STOPWORDS